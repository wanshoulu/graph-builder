# ── 辅助函数 ──────────────────────────────────────────────

def set_col_widths(ws, widths):
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w

def write_header(ws, row, headers, desc_list=None):
    for col, h in enumerate(headers, 1):
        c = ws.cell(row=row, column=col, value=h)
        c.font = HEADER_FONT
        c.fill = HEADER_FILL
        c.alignment = CENTER
        c.border = BORDER
    ws.row_dimensions[row].height = 26
    if desc_list:
        dr = row + 1
        for col, d in enumerate(desc_list, 1):
            c = ws.cell(row=dr, column=col, value=d)
            c.font = DESC_FONT
            c.fill = DESC_FILL
            c.alignment = CENTER
            c.border = BORDER
        ws.row_dimensions[dr].height = 46

def write_example_row(ws, row, values, fill=EXAMPLE_FILL, font=EXAMPLE_FONT):
    for col, v in enumerate(values, 1):
        c = ws.cell(row=row, column=col, value=v)
        c.font = font
        c.fill = fill
        c.alignment = LEFT
        c.border = BORDER
    ws.row_dimensions[row].height = 24

def add_dv(ws, formula, col_letter, start_row, end_row=500):
    dv = DataValidation(type='list', formula1=formula, allow_blank=True)
    dv.add(f'{col_letter}{start_row}:{col_letter}{end_row}')
    ws.add_data_validation(dv)

